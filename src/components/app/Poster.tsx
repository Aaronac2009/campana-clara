import { useMemo } from "react";
import { posterLayout, type PosterImage } from "@/lib/poster";
import { useCampaignImage } from "@/lib/campaign-image";
import { useStore } from "@/lib/store";
import type { FormatKey, Profile } from "@/lib/types";

type PosterCampaign = Parameters<typeof posterLayout>[0];

export function Poster({ campaign, profile, format, className, image }: { campaign: PosterCampaign; profile: Profile; format: FormatKey; className?: string; image?: PosterImage | null }) {
  const { media, t } = useStore();
  const resolved = useCampaignImage(image === undefined ? campaign.image : undefined, media);
  const img = image === undefined ? resolved.image : image;
  const layout = useMemo(() => posterLayout(campaign, profile, format, img), [campaign, profile, format, img]);
  return (
    <div
      className={className}
      style={{ aspectRatio: `${layout.w} / ${layout.h}` }}
      role="img"
      aria-label={`${t('Vista previa del afiche')}: ${campaign.title}`}
      // Safe: markup is generated by posterLayout with all text escaped; no user SVG is ever inserted.
      dangerouslySetInnerHTML={{ __html: layout.svg.replace("<svg ", '<svg style="width:100%;height:100%;display:block" ') }}
    />
  );
}
